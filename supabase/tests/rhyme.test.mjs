// Тест рифмы: проверяет настоящий код из supabase/functions/_shared/rhyme.ts.
// Запуск из корня репозитория:  node supabase/tests/rhyme.test.mjs
// Как добавить свой случай: допиши строку в cases — [название, текст A, слоги A, текст B, слоги B, ожидание].
// «Ожидание» — примерный балл; проверка считается пройденной, если факт попал
// в допуск ±1 балл (погрешность). Поставь null, если хочешь просто увидеть балл без проверки.

import { pairRhyme, rhymeScore } from '../functions/_shared/rhyme.ts'

const cases = [
  ['низко/близко (богатая рифма)', 'Ты был очень близко', 6, 'а теперь низко', 5, 10],
  ['тапки/бабки (богатая, п≡б)', 'Твой флоу, бро, — домашние тапки', 10, 'Ты копишь на кроссы, я кручу бабки', 11, 10],
  ['ок/игрок, длины 11/10', 'Ты в бою как нищий — пустой кошелёк', 11, 'А я на сцене — ты просто игрок', 10, 9],
  ['ок/игрок, длины 10/16 (штраф за длину)', 'Ты пустой кошелёк', 10, 'А я на сцене очень длинная строка прямо игрок', 16, 5],
  ['up-up/dumb (латиница + сонорант)', 'Окей, я был очень низко, а теперь up-up', 15, 'Окей, зачем ты так близко? Отойди, ты dumb', 15, 8.5],
  ['имя/могила (гласные совпали)', 'кричат твоё имя', 6, 'всё ближе могила', 6, 9.5],
  ['ап/амп (сонорант м)', 'я собираю кэш ап', 7, 'ты всегда амп', 4, 4],
  ['затих/брат (без рифмы)', 'Я выхожу на бит, и район затих', 11, 'Ты зовёшь это рэпом? Смешно, брат', 10, 0.5],
  ['шум/игрок (хвост не тот)', 'фоновый шум', 4, 'ты просто игрок', 5, 0.5],
  ['насрать/стандарт', 'Подустал? Нам насрать!', 6, 'Тони Старк как стандарт', 6, 6],
]

let failures = 0
for (const [name, textA, sylA, textB, sylB, expected] of cases) {
  const got = pairRhyme({ text: textA, syllables: sylA }, { text: textB, syllables: sylB })
  if (expected === null) {
    console.log(`     ${name}: ${got}`)
    continue
  }
  const ok = Math.abs(got - expected) <= 1
  if (!ok) failures++
  console.log(`${ok ? 'OK   ' : 'FAIL '} ${name}: ${got} (ожидалось ${expected})`)
}

// Итог раунда целиком: среднее двух пар строк (1-2 и 3-4)
const round = [
  { text: 'Ты в бою как нищий — пустой кошелёк', syllables: 11 },
  { text: 'А я на сцене — ты просто игрок', syllables: 10 },
  { text: 'Ты копишь на кроссы, я кручу бабки', syllables: 11 },
  { text: 'Твой флоу, бро, — домашние тапки', syllables: 10 },
]
console.log(`\nраунд из docs/api.md: рифма = ${rhymeScore(round)}\n`)

if (failures) {
  console.log(`Провалено проверок: ${failures}`)
  process.exit(1)
}
console.log('Все проверки пройдены.')
