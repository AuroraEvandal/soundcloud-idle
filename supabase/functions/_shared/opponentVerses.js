export function opponentVerse(opponentId, battleId, roundNumber) {
  const verses = VERSES[opponentId]
  if (!verses) return null
  // Stable per battle; consecutive rounds cannot repeat a verse.
  let offset = 0
  for (const char of battleId) offset = (offset * 31 + char.charCodeAt(0)) >>> 0
  return [...verses[(offset + roundNumber - 1) % verses.length]]
}
